import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, posix } from 'node:path';

import type { Manifest, ManifestItem } from '../registry/schema';

import { type LoomConfig, targetPath } from './config';

/** The index file inside the sandbox folder, next to the template's `demos.types.ts`. */
export const SANDBOX_INDEX = 'demos.ts';

/** Sandbox section: the theme item's demos, then everything else. */
export type DemoGroup = 'theme' | 'components';

export type IndexedDemo = {
  /** Route segment `/sandbox/<id>`, from `demoId`. */
  id: string;
  group: DemoGroup;
  /** Project-relative path of the demo file. */
  target: string;
};

/** The item name for an item's only demo; `<item>-<file name>` when it has several. */
export const demoId = (name: string, demos: string[], path: string) => {
  if (demos.length === 1) return name;
  const file = posix.basename(path).replace(/\.demo\.[cm]?[jt]sx?$/, '');
  return `${name}-${file.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()}`;
};

export const demoGroup = (item: ManifestItem): DemoGroup =>
  item.kind === 'theme' ? 'theme' : 'components';

/** An item's demos with their ids, groups and project paths. */
export const itemDemos = (
  name: string,
  item: ManifestItem,
  target: (path: string) => string
): IndexedDemo[] =>
  item.demos.map((path) => ({
    id: demoId(name, item.demos, path),
    group: demoGroup(item),
    target: target(path),
  }));

const identifier = (id: string) =>
  `${id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Demo`;

// Expo maps `@/*` to `src/*`; in the monorepo template it also reaches packages/ui.
const specifier = (sandbox: string, target: string) => {
  const path = target.replace(/\.[cm]?[jt]sx?$/, '');
  if (path.startsWith('src/')) return `@/${path.slice('src/'.length)}`;
  const relative = posix.relative(sandbox, path);
  return relative.startsWith('.') ? relative : `./${relative}`;
};

/** Source of the sandbox index for these demos, sorted by id and formatted as Prettier would. */
export const renderSandboxIndex = (
  sandbox: string,
  demos: IndexedDemo[]
): string => {
  const sorted = [...demos].sort((a, b) => a.id.localeCompare(b.id));
  const imports = sorted.map(
    ({ id, target }) =>
      `import { demo as ${identifier(id)} } from '${specifier(sandbox, target)}';\n`
  );
  const entries = sorted.map(
    ({ id, group }) =>
      `{ id: '${id}', group: '${group}', ...${identifier(id)} }`
  );

  const head = 'export const demos: readonly DemoEntry[] = ';
  const inline = `${head}[${entries.join(', ')}];`;
  const list =
    entries.length < 2 && inline.length <= 80
      ? `${inline}\n`
      : `${head}[\n${entries.map((e) => `  ${e},\n`).join('')}];\n`;

  return [
    '// Generated by loom from loom.json: `loom add` rewrites this file.\n',
    imports.length ? `${imports.join('')}\n` : '',
    "import type { DemoEntry } from './demos.types';\n\n",
    '/** Sandbox index, grouped and filtered by the sandbox screen. */\n',
    list,
  ].join('');
};

/** Demos of the items recorded in `loom.json` whose file is in the project. */
export const installedDemos = async (
  cwd: string,
  manifest: Manifest,
  config: LoomConfig
): Promise<IndexedDemo[]> => {
  const demos: IndexedDemo[] = [];
  for (const name of Object.keys(config.items)) {
    const item = manifest.items[name];
    if (!item) continue;
    for (const demo of itemDemos(name, item, (p) => targetPath(config, p))) {
      // Items added before `sandbox` was set have no demo file.
      const present = await access(join(cwd, demo.target)).then(
        () => true,
        () => false
      );
      if (present) demos.push(demo);
    }
  }
  return demos;
};

/** Rewrites the sandbox index from `loom.json`. Returns its path when the content changed. */
export const writeSandboxIndex = async (
  cwd: string,
  manifest: Manifest,
  config: LoomConfig
): Promise<string | undefined> => {
  if (!config.sandbox) return undefined;
  const target = posix.join(config.sandbox, SANDBOX_INDEX);
  const file = join(cwd, target);
  const content = renderSandboxIndex(
    config.sandbox,
    await installedDemos(cwd, manifest, config)
  );
  const current = await readFile(file, 'utf8').catch(() => undefined);
  if (current === content) return undefined;
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content);
  return target;
};

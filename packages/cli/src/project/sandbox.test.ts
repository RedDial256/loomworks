import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';

import { manifestSchema } from '../registry/schema';

import { defaultConfig, targetPath } from './config';
import { renderSandboxIndex } from './sandbox';

const box = { id: 'box', target: 'src/components/box/Box.demo.tsx' };

describe('renderSandboxIndex', () => {
  it('writes an empty index', () => {
    expect(renderSandboxIndex('src/sandbox', [])).toBe(
      `// Generated by loom from loom.json: \`loom add\` rewrites this file.
import type { DemoEntry } from './demos.types';

/** Sandbox index, filtered by the drawer search. */
export const demos: readonly DemoEntry[] = [];
`
    );
  });

  it('sorts demos by id and imports them by a camelCase name', () => {
    const motion = {
      id: 'reduced-motion',
      target: 'src/hooks/reduced-motion/useReducedMotion.demo.tsx',
    };
    const index = renderSandboxIndex('src/sandbox', [motion, box]);
    expect(index).toContain(
      `import { demo as boxDemo } from '@/components/box/Box.demo';
import { demo as reducedMotionDemo } from '@/hooks/reduced-motion/useReducedMotion.demo';
`
    );
    expect(index).toContain(`[
  { id: 'box', ...boxDemo },
  { id: 'reduced-motion', ...reducedMotionDemo },
];
`);
  });

  it('imports relatively outside src', () => {
    const demo = { id: 'box', target: 'app/ui/components/box/Box.demo.tsx' };
    expect(renderSandboxIndex('app/sandbox', [demo])).toContain(
      "from '../ui/components/box/Box.demo';"
    );
  });
});

describe('template sandbox index', () => {
  // The monorepo template lists every demo of the kit. Run `vitest -u` after adding one.
  it('lists every demo in the UI manifest', async () => {
    const manifest = manifestSchema.parse(
      JSON.parse(
        await readFile(
          new URL('../../../ui/manifest.json', import.meta.url),
          'utf8'
        )
      )
    );
    const config = { ...defaultConfig(), sandbox: 'src/sandbox' };
    const demos = Object.entries(manifest.items).flatMap(([id, item]) =>
      item.demo ? [{ id, target: targetPath(config, item.demo) }] : []
    );
    await expect(renderSandboxIndex(config.sandbox, demos)).toMatchFileSnapshot(
      '../../../../templates/app/src/sandbox/demos.ts'
    );
  });
});
